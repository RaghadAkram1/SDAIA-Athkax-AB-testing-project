"""Day 1 — Declare the research design before seeing any outcome data."""
from dataclasses import asdict, dataclass
from pathlib import Path
import json

BASE = Path(__file__).resolve().parents[1]

@dataclass(frozen=True)
class Study:
    title: str = 'قياس أثر المساعد الذكي على إكمال الخدمات الإلكترونية'
    question: str = 'هل تؤدي إتاحة مساعد ذكي إلى زيادة إكمال الخدمة خلال 24 ساعة؟'
    population: str = 'الحسابات المؤهلة عند أول بدء للخدمة الإلكترونية الافتراضية'
    estimand: str = 'فرق نسب الإكمال وفق ITT: المعالجة ناقص المقارنة'
    assignment_unit: str = 'حساب مؤهل واحد وتوزيع ثابت واحد'
    baseline_rate: float = 0.60
    meaningful_gain: float = 0.05
    alpha: float = 0.05
    target_power: float = 0.80
    allocation_to_ai: float = 0.50
    new_users_daily: int = 500
    minimum_weeks: int = 2
    safety_margin: float = 0.02
    random_seed: int = 7112026
    hypothetical_ai_effect: float = 0.055
    hypothetical_error_effect: float = 0.002
    hypothetical_support_effect: float = -0.009

RESEARCH_NOTES = '''# اليوم الأول | السؤال البحثي وتصميم التجربة

## 0. بيانات المشروع
- **عنوان المشروع:** قياس أثر إتاحة مساعد ذكاء اصطناعي على إكمال الخدمات الإلكترونية.
- **الدورة:** التجارب واختبارات A/B والاستدلال السببي — أكاديمية سدايا.
- **المشاركون:** يضاف الاسم قبل التسليم.
- **المنتج:** خدمة إلكترونية افتراضية واحدة.
- **مصدر البيانات:** بيانات محاكاة لا تتضمن معلومات حقيقية أو شخصية.

## 1. المشكلة والقرار والسؤال
تواجه بعض الخدمات الإلكترونية انسحاب المستخدمين قبل إكمال الطلبات. نختبر ما إذا كان **توفير** مساعد اختياري يشرح الخطوات ويساعد على تجاوز الغموض يحسن النتيجة.

**القرار:** هل نوصي بإتاحة المساعد لجميع المستخدمين، أم لا؟  
**السؤال:** هل تؤدي إتاحة مساعد ذكي في واجهة الخدمة إلى زيادة إكمال الخدمة خلال 24 ساعة مقارنةً بالواجهة الحالية؟  
**الفرضية التفسيرية:** قد تقل الحاجة لفهم الإجراءات من دون مساعدة، فيقل الانسحاب ويرتفع معدل الإكمال.  
**الفرضية الصفرية H0:** لا فرق بين نسب الإكمال في A وB.  
**الفرضية البديلة H1:** يوجد فرق بين النسبتين (اختبار ثنائي الطرف)، ونتوقع أن يكون لصالح B.

**ما الذي يغيّر رأينا؟** عدم تحقق تحسن موثوق ذي قيمة عملية، أو عدم القدرة على استبعاد تدهور مؤثر في مقاييس الحماية، أو إخفاق فحوص جودة التجربة.

## 2. تصميم الدراسة
- **المجتمع المستهدف:** الحسابات المؤهلة التي تبدأ الخدمة الافتراضية للمرة الأولى خلال الدراسة.
- **وحدة العشوائية:** حساب مستخدم فريد، وليس الزيارة أو الجلسة.
- **وحدة التحليل:** حساب واحد يمثل محاولة بدء واحدة، ويُحتسب إكمال الخدمة خلال نافذة 24 ساعة.
- **المقارنة A:** الواجهة الحالية دون مساعد ذكي.
- **المعالجة B:** نفس الواجهة مع إتاحة مساعد اختياري للإرشاد.
- **التوزيع:** 50/50 عبر SHA-256 لمعرّف الحساب مع قيمة ثابتة لضمان عدم التبديل بين الزيارات.
- **المعالجة المقاسة:** **إتاحة المساعد**، وليس مجرد فتحه؛ وذلك حفاظًا على المقارنة العشوائية (ITT).
- **المقياس الرئيسي:** نسبة الإكمال خلال 24 ساعة، محسوبة على كل الحسابات الموزعة.
- **مقاييس الحماية:** نسبة مواجهة خطأ ونسبة التواصل مع الدعم البشري، بين جميع الحسابات الموزعة.
- **مقاييس إضافية:** فتح المساعد، والاختلاف عبر الأيام، والمدة لدى من أكملوا (وصفيًا فقط).
- **متغير سابق للمعالجة:** عدد الزيارات السابقة للمستخدم للتحقق عبر ANCOVA.
- **مدة التجربة:** تُحدد في اليوم الثاني بناءً على القدرة الإحصائية وتدفق المستخدمين المتوقع.

## متطلبات الاستدلال السببي
- **SUTVA:** لا يؤثر تخصيص مستخدم على نتائج مستخدم آخر، ولا توجد نسخ مختلفة غير موثقة من المساعد.
- **اتساق التنفيذ:** جميع قواعد الخدمة ثابتة بين A وB، ما عدا إتاحة المساعد.
- **عدم اختيار المشاركين بعد المعالجة:** يبقى المستخدمون الذين لم يفتحوا المساعد في B ضمن التحليل الأساسي.
- **توثيق المخرجات:** نافذة 24 ساعة مكتملة لكل مستخدم، مع منع التكرار وفقد بيانات النتائج الإلزامية.
- **الإيقاف:** عدم الفحص المتكرر بهدف اختيار أول قيمة p دالة؛ التحليل بعد نهاية المدة المقررة.

## خطة التحليل المكتوبة مسبقًا
1. نفحص صحة البيانات ونسبة التوزيع المتوقعة 50/50 باستخدام SRM عند حد 0.001.
2. نقدر فرق نسب الإكمال (B−A) وفق ITT، مع اختبار ثنائي الطرف وفترة ثقة 95%.
3. نستخدم ANCOVA بضبط الزيارات السابقة للتحقق الاستكشافي من ثبات النتيجة، لا لاستبدال التحليل الأساسي.
4. نفحص الأخطاء والدعم: يجب أن يكون الحد الأعلى لفترة ثقة الفرق في كل منهما أقل من **+2 نقطة مئوية**.
5. نتخذ قرارًا مبدئيًا حول الإطلاق فقط إن كان الحد الأدنى لفترة الثقة في الإكمال أكبر من صفر، والتقدير النقطي للتحسن لا يقل عن **+5 نقاط مئوية**، ومقاييس الحماية مقبولة.
6. إذا كان الفرق غير حاسم، نوصي بتجربة لاحقة مخططة بدل ادعاء وجود أثر أو عدمه.

**تنبيه:** جميع معدلات الخط الأساس وآثار المحاكاة المفترضة لأغراض تعليمية؛ لا توجد نتائج حقيقية عن خدمة أو جهة محددة.
'''

def run():
    study = Study()
    output = BASE / 'outputs/results'
    output.mkdir(parents=True, exist_ok=True)
    (output/'study_spec.json').write_text(json.dumps(asdict(study), indent=2), encoding='utf-8')
    (output/'day_01_protocol.md').write_text(RESEARCH_NOTES, encoding='utf-8')
    print('[اليوم الأول] تم حفظ تصميم التجربة وخطة التحليل المسبقة')
    return study

if __name__ == '__main__':
    run()
